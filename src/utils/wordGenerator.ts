/**
 * Generates a unique, memorable two-word subdomain like `lagoon-player` or `cobalt-beacon`.
 */
export function generateRandomSubdomain(existingSubdomains?: Set<string>): string {
  for (let attempt = 0; attempt < 100; attempt++) {
    const adj = ADJECTIVES[Math.floor(Math.random() * ADJECTIVES.length)];
    const noun = NOUNS[Math.floor(Math.random() * NOUNS.length)];
    const candidate = `${adj}-${noun}`.toLowerCase();
    if (containsDisallowedWords(candidate)) {
      continue;
    }
    if (!existingSubdomains || !existingSubdomains.has(candidate)) {
      return candidate;
    }
  }
  const adj = ADJECTIVES[Math.floor(Math.random() * ADJECTIVES.length)];
  const noun = NOUNS[Math.floor(Math.random() * NOUNS.length)];
  const suffix = Math.floor(10 + Math.random() * 90);
  const fallback = `${adj}-${noun}-${suffix}`.toLowerCase();
  if (containsDisallowedWords(fallback)) {
    return `amber-haven-${suffix}`;
  }
  return fallback;
}
