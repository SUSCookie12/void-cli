import fs from 'node:fs/promises';
import path from 'node:path';
import { getServerDir } from '../utils/paths.js';

export interface ServerProperties {
  [key: string]: string;
}

const DEFAULT_PROPERTIES: ServerProperties = {
  'gamemode': 'survival',
  'difficulty': 'easy',
  'pvp': 'true',
  'max-players': '20',
  'server-port': '25565',
  'level-name': 'world',
  'level-seed': '',
  'level-type': 'default',
  'online-mode': 'true',
  'allow-flight': 'false',
  'motd': 'A Void Minecraft Server',
  'view-distance': '10',
  'simulation-distance': '10',
  'generate-structures': 'true',
  'allow-nether': 'true',
  'hardcore': 'false',
  'spawn-monsters': 'true',
  'spawn-animals': 'true',
  'spawn-npcs': 'true',
  'white-list': 'false'
};

export async function readProperties(serverName: string): Promise<ServerProperties> {
  const dir = getServerDir(serverName);
  const filePath = path.join(dir, 'server.properties');

  const props: ServerProperties = { ...DEFAULT_PROPERTIES };

  try {
    const content = await fs.readFile(filePath, 'utf-8');
    const lines = content.split('\n');

    for (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      
      const firstEq = trimmed.indexOf('=');
      if (firstEq === -1) continue;

      const key = trimmed.substring(0, firstEq).trim();
      const value = trimmed.substring(firstEq + 1).trim();
      props[key] = value;
    }
  } catch (err) {
    // If file doesn't exist, we just return the defaults
  }
  
  return props;
}

export async function writeProperties(serverName: string, props: ServerProperties): Promise<void> {
  const dir = getServerDir(serverName);
  const filePath = path.join(dir, 'server.properties');

  const existing = await readProperties(serverName);
  const merged = { ...existing, ...props };

  let output = '# Minecraft server properties\n# Generated by Void Server Dashboard\n';
  
  // Sort keys for consistent output
  const keys = Object.keys(merged).sort();
  for (const key of keys) {
    output += `${key}=${merged[key]}\n`;
  }

  await fs.writeFile(filePath, output, 'utf-8');
}
